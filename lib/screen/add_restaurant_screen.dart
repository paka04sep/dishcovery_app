    Map<String, dynamic> tempHours = Map<String, dynamic>.from(
      _openingHours.map((k, v) {
        if (v is List) {
          // Backwards compatibility from formatted structure
          if (v.isEmpty)
            return MapEntry(k, {
              'open': '09:00',
              'close': '20:00',
              'isClosed': true,
            });
          return MapEntry(k, {
            'open': v.first['open'],
            'close': v.first['close'],
            'isClosed': false,
          });
        }
        return MapEntry(k, Map<String, dynamic>.from(v));
      }),
    );

