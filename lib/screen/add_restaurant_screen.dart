      'อาทิตย์',
    ];

    // Initialize defaults if empty
    if (_openingHours.isEmpty) {
      for (var day in days) {
        _openingHours[day] = {
          'open': '09:00',
          'close': '20:00',
          'isClosed': false,
        };
      }
    }

